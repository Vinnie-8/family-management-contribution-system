"""
RegistrationCode — a one-time code that lets someone create a new family.
Generated by the platform admin (a script), handed to a future Chairman.
Stored hashed, single-use, expiring. Not tied to any family until it is used.
"""
import uuid

from sqlalchemy import Column, DateTime, ForeignKey, String
from sqlalchemy.dialects.postgresql import UUID
from sqlalchemy.sql import func

from app.database import Base


class RegistrationCode(Base):
    __tablename__ = "registration_codes"

    id = Column(UUID(as_uuid=True), primary_key=True, default=uuid.uuid4)
    code_hash = Column(String(64), nullable=False, unique=True)
    note = Column(String(100), nullable=True)  # who the code was issued to
    expires_at = Column(DateTime(timezone=True), nullable=False)
    used_at = Column(DateTime(timezone=True), nullable=True)
    used_by_family_id = Column(UUID(as_uuid=True), ForeignKey("families.id", ondelete="SET NULL"), nullable=True)
    created_at = Column(DateTime(timezone=True), server_default=func.now(), nullable=False)